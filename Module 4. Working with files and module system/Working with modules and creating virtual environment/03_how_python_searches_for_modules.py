# Тема: Як взагалі Python шукає модулі? (How does Python search for modules?)
# Розглянуто: Python шукає модулі в такому порядку: 1) папка скрипту, 2) PYTHONPATH, 3) папки інсталяції; sys.path — список цих шляхів
# -----------------------------------------------

'''
Коли ви використовуєте оператор import для завантаження модуля, Python шукає відповідний файл .py за допомогою визначеного порядку пошуку.

Перш за все, Python шукає модуль у директорії, з якої запускається виконавчий скрипт (або поточній робочій директорії, якщо інтерпретатор запущений інтерактивно).

Далі пошук відбувається в змінній оточення PYTHONPATH. Це змінна оточення, яка містить список директорій, що Python переглядає під час пошуку модулів. Це схоже на змінну PATH в операційних системах, що визначає шляхи до виконавчих файлів. PYTHONPATH дає можливість додавати додаткові директорії, де Python може шукати модулі, які не знаходяться у стандартному місці.

! ☝ Змінні оточення під час запуску програми використовуються для забезпечення конфіденційності даних, налаштування конфігурації та адаптації поведінки програми до різних середовищ. Ці змінні є частиною оточення, в якому виконується програма, і можуть бути встановлені або змінені на рівні операційної системи, командного рядка або безпосередньо у коді програми.

Якщо модуль не було знайдено, то Python, в кінці, перевіряє директорії, які були визначені під час його інсталяції. Ці директорії зазвичай включають місця, де знаходяться стандартні бібліотеки Python.

Цей процес дозволяє Python ефективно знаходити та завантажувати модулі з різних місць.

Отже окремі файли з розширенням .py — це модулі. Ви можете імпортувати з них потрібні вам сутності (об'єкти, константи тощо) і використати в інших модулях. Зверніть увагу, що під час імпорту не потрібно вказувати розширення файлу .py, тільки ім'я.
'''

#--------------------------------------------------------------------------------#

'''Завдання: Як взагалі Python шукає модулі?

1. Імпортуй модуль sys
2. Виведи sys.path — список шляхів де Python шукає модулі
3. Пиши сам, показуй коли готово.
'''

# sys — вбудований модуль Python, імпортується без from
import sys

# sys.path — список директорій де Python шукає модулі при import
print(sys.path)