'''
Модулем Python є будь-який текстовий файл з розширенням py, який містить код мовою Python. Це означає, що коли ви створюєте скрипт mymodule.py, який містить ось такий код:
'''

# mymodule.py
def say_hello(name):
    return f"Hello, {name}!"

'''
В цьому файлі ми визначили функцію say_hello, яка приймає один аргумент name і повертає привітання. Кожен модуль має свій простір імен, що відокремлює його визначення від інших модулів. Наприклад, якщо в іншому модулі існує функція з такою ж назвою, це не призведе до конфлікту.

Для використання цього модуля в іншому файлі Python, наприклад в main.py, ми імпортуємо його:

# main.py
import mymodule

print(mymodule.say_hello("World"))

Тут mymodule.say_hello("World") викликає функцію say_hello з модуля mymodule всередині скрипту main.py.
'''
'''
Ви також можете імпортувати функцію say_hello з mymodule.py за допомоги виразу from mymodule import say_hello у будь-якому скрипті в тій самій директорії, що і mymodule.py.

# main.py
from mymodule import say_hello

print(say_hello("World"))
'''
'''
Ми також можемо змінити назву функції say_hello всередині main.py, коли імпортуємо її з модуля mymodule.py

# main.py
from mymodule import say_hello as greeting

print(greeting("World"))

У цьому прикладі, функція say_hello імпортується з модуля mymodule.py, але замість того, щоб використовувати її безпосередньо як say_hello , ми надаємо їй псевдонім greeting. Тепер у нашому коді ми можемо використовувати greeting для виводу сповіщення.

Така конструкція використовується для імпортування конкретного елемента, а це може бути функція, клас, змінна тощо з модуля, і одночасно присвоєння цьому елементу псевдоніму (alias) у нашому коді.

from module_name import item_name as alias


Це корисно з декількох причин:

1. Головна причина, це уникнення конфліктів імен. Якщо у вашому коді вже існує елемент з таким самим іменем, як і імпортований, ви можете використовувати псевдонім, щоб уникнути конфлікту імен.
2. Спрощення вашого коду. Іноді імена класів або функцій у модулях можуть бути довгими або не зовсім зрозумілими. Використання псевдоніму може зробити ваш код чистішим і легшим для розуміння.
3. Інколи ви захочете замінити модуль на інший з аналогічним функціоналом. Тоді достатньо буде змінити тільки рядок імпорту, зберігаючи той самий псевдонім в вашому коді.
'''

#--------------------------------------------------------------------------------#

