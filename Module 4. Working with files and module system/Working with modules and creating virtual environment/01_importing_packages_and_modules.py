'''Завдання: Імпорт пакетів та модулів

1. Імпортуй модуль math і виведи значення math.pi
2. Використай math.sqrt() щоб обчислити корінь з 144 і виведи результат
3. Імпортуй з math тільки floor і ceil через from ... import ...
4. Виведи floor(3.7) і ceil(3.2)
5. Пиши сам, показуй коли готово.
'''
# from math import pi — імпортує тільки pi, без префікса модуля
from math import pi
print(pi)  # 3.141592653589793

# from math import sqrt — альтернатива до math.sqrt(), результат той самий
from math import sqrt
sqrt_144 = sqrt(144)
print(sqrt_144)  # 12.0

# from ... import ... — імпорт кількох імен одразу через кому
from math import floor, ceil

# floor() — округлює вниз до цілого
floor_test1 = floor(3.7)
print(floor_test1)  # 3

# ceil() — округлює вгору до цілого
ceil_test2 = ceil(3.2)
print(ceil_test2)  # 4
