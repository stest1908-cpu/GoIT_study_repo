# Розглянуто: dir(module) — список атрибутів і методів модуля; dir() без аргументів — імена у поточній області видимості
# -----------------------------------------------

'''
Функція dir() в Python використовується для отримання переліку атрибутів (включно з методами) об'єкта чи модуля. Це корисно для розуміння того, що доступно в модулі після його імпортування:

- dir(module_name): Повертає список атрибутів, визначених у модулі module_name.
Без аргументів, dir() повертає список атрибутів з поточної області визначень.

- Вбудована функція dir() повертає список визначених імен у просторі імен. Без аргументів вона виробляє алфавітно відсортований список імен у поточній локальній таблиці символів:


# main.py
from mymodule import say_hello as greeting

print(dir())
print(greeting("World"))


Коли ми викликаємо функцію dir() без аргументів усередині модуля, вона повертає список назв усіх об'єктів (змінних, функцій, класів тощо), доступних у поточній області видимості. Фактично, що доступно в середині файлу main.py під час запуску. У нашому випадку, це включає зокрема вбудовані імена, такі як __annotations__, __builtins__, тощо і псевдонім greeting, який ми створили для функції say_hello з модуля mymodule.py.


['__annotations__', '__builtins__', '__cached__', '__doc__', '__file__', '__loader__', '__name__', '__package__', '__spec__', 'greeting']
Hello, World!


Зазначене виведення ['__annotations__', '__builtins__', '__cached__', '__doc__', '__file__', '__loader__', '__name__', '__package__', '__spec__', 'greeting']) показує список доступних вам імен. Але цей список не включає імена, які містяться в модулі mymodule, оскільки ми імпортували лише одну його функцію, а не весь модуль.
'''

#--------------------------------------------------------------------------------#

'''Завдання: Функція dir()

1. Імпортуй модуль math
2. Виведи dir(math) — список всього що є в модулі
3. Виведи dir() без аргументів — список імен у поточній області видимості
4. Пиши сам, показуй коли готово.
'''

# import math — імпортуємо весь модуль щоб передати його в dir()
import math

# dir(math) — виводить всі атрибути і функції модуля math
print(dir(math))

# dir() без аргументів — виводить імена доступні в поточному файлі
print(dir())