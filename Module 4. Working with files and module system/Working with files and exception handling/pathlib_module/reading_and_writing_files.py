'''Завдання: Читання та запис файлів

1. Створи шлях до файлу "notes.txt" через Path()
2. Запиши в нього текст "Моя перша нотатка" через write_text() з encoding="utf-8"
3. Прочитай текст з цього файлу через read_text() і виведи його
4. Створи шлях до файлу "data.bin" через Path()
5. Запиши в нього байти b"Hello bytes" через write_bytes()
6. Прочитай байти з цього файлу через read_bytes() і виведи їх
7. Пиши сам, показуй коли готово.
'''

from pathlib import Path

# Шлях до текстового файлу
notes_path = Path("notes.txt")

# write_text() — записує рядок у файл, створює файл якщо не існує
notes_path.write_text("Моя перша нотатка", encoding="utf-8")

# read_text() — читає вміст файлу як рядок
text = notes_path.read_text(encoding="utf-8")
print(text)  # Моя перша нотатка

# Шлях до бінарного файлу
data_path = Path("data.bin")

# write_bytes() — записує байти (b"...") у файл
data_path.write_bytes(b"Hello bytes")

# read_bytes() — читає вміст файлу як байти
binary_data = data_path.read_bytes()
print(binary_data)  # b'Hello bytes'