'''Завдання: Масив байтів

1. Створи bytearray з рядка b'Hello World'
2. Зміни перший символ на 'J' (використай ord())
3. Додай символ '!' в кінець (використай append())
4. Виведи результат
5. Декодуй bytearray у звичайний рядок і виведи
6. Пиши сам, показуй коли готово.
'''
# Створюємо bytearray з байт-рядка — змінний масив байтів
my_byte_array = bytearray(b'Hello World')

# Змінюємо перший байт: ord('J') повертає числовий код символу 'J' = 74
my_byte_array[0] = ord('J')

# Додаємо символ '!' в кінець масиву
my_byte_array.append(ord('!'))

# Декодуємо bytearray у звичайний рядок і виводимо
my_string = my_byte_array.decode("utf-8")
print(my_string)  # Виведе: Jello World!
