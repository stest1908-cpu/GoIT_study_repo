'''Завдання: калькулятор через словник функцій

1. Напиши 4 функції: add(a, b), subtract(a, b), multiply(a, b), divide(a, b) - звичайні
   математичні операції над двома числами.
2. Створи словник operations, де ключі - це рядки "+", "-", "*", "/", а значення -
   відповідні функції (без виклику, просто посилання на функцію, як у прикладі вище).
3. Напиши функцію calculate(a, b, op), яка приймає два числа та рядок з операцією ("+","-" тощо),
   знаходить потрібну функцію в operations за ключем op і викликає її з аргументами a, b.
4. Перевір на прикладах:
      print(calculate(10, 5, "+"))    # 15
      print(calculate(10, 5, "-"))    # 5
      print(calculate(10, 5, "*"))    # 50
      print(calculate(10, 5, "/"))    # 2.0

Готового рішення поки нема — напиши свій варіант нижче, я перевірю.
'''
from typing import Callable, Dict

# 4 звичайні математичні операції
def add(a: int, b: int) -> int:
    return a + b

def subtract(a: int, b: int) -> int:
    return a - b

def multiply(a: int, b: int) -> int:
    return a * b

def divide(a: int, b: int) -> int:
    return a / b

# Словник операцій: ключ - символ операції, значення - сама функція (без виклику)
operations: Dict[str, Callable] = {
    '+': add,
    '-': subtract,
    '*': multiply,
    '/': divide
}

def calculate(a: int, b: int, op: str) -> int:
    # operations[op] дістає потрібну функцію зі словника, (a, b) одразу її викликає
    return operations[op](a, b)

print(calculate(10, 5, "+"))    # 15
print(calculate(10, 5, "-"))    # 5
print(calculate(10, 5, "*"))    # 50
print(calculate(10, 5, "/"))    # 2.0