'''Завдання: namedtuple Book

1. Створи іменований кортеж Book з полями: title, author, year.
2. Створи список із 3-4 екземплярів Book (вигадай книги сам).
3. Пройдися по списку циклом for і виведи кожну книгу у форматі:
      "1984" (1949) - George Orwell
   (рік у дужках, назва в лапках, використовуй f-string і поля за іменем, не за індексом).
4. Знайди й виведи книгу з найменшим роком видання (підказка: можна використати min()
   з параметром key, наприклад: min(books, key=lambda b: b.year)).

Готового рішення поки нема — напиши свій варіант нижче, я перевірю.
'''

import collections

# Створення іменованого кортежу Book з полями title, author, year
books = collections.namedtuple('books', ['title', 'author', 'year'])

# Створення 4 екземплярів Book
book1 = books('1984', 'George Orwell', '1949')
book2 = books('The Hobbit', 'J.R.R. Tolkien', '1937')
book3 = books('Dune', 'Frank Herbert', '1965')
book4 = books('Fahrenheit 451', 'Ray Bradbury', '1953')

# Список усіх книг, щоб можна було пройтись по них циклом
books_list = [book1, book2, book3, book4]

# Виведення кожної книги у форматі "Назва" (рік) - Автор
for book in books_list:
    print(f'"{book.title}" ({book.year}) - {book.author}')

# Пошук книги з найменшим роком видання: key=lambda b: b.year каже min(),
# що порівнювати книги треба саме за полем year, а не самі об'єкти
oldest_book = min(book1, book2, book3, book4, key=lambda b: b.year)
print(f'{oldest_book.title} ({oldest_book.year}) - {oldest_book.author}')
