'''Завдання: перевірка балансу дужок через стек

Класична задача, де стек застосовують на практиці - перевірка, чи правильно розставлені
дужки в рядку (кожна відкриваюча дужка має свою закриваючу, і вони не переплутані).

1. Використай уже готові функції create_stack, is_empty, push, pop з цього файлу.
2. Напиши функцію is_balanced(expression), яка перевіряє рядок з дужками "()", "[]", "{}":
   - Проходь по рядку символ за символом.
   - Якщо символ - відкриваюча дужка ( ( [ { ) - робиш push у стек.
   - Якщо символ - закриваюча дужка ( ) ] } ) - робиш pop зі стека і перевіряєш,
     чи вилучена дужка відповідає поточній закриваючій (наприклад для ')' очікуємо '(').
     Якщо не відповідає, або стек уже порожній - рядок незбалансований (return False).
   - В кінці, якщо стек порожній - рядок збалансований (return True), інакше - False.
3. Перевір функцію на прикладах:
      print(is_balanced("(a+b)*[c-d]"))     # True
      print(is_balanced("([a+b)]"))          # False
      print(is_balanced("{[()]}"))           # True
      print(is_balanced("(("))               # False

Готового рішення поки нема — напиши свій варіант нижче, я перевірю.
'''

def is_balanced(expression):
    # Порожній стек - сюди будемо класти відкриваючі дужки по черзі
    stack = create_stack()

    # Словник відповідностей: за закриваючою дужкою дізнаємось, яка відкриваюча їй потрібна
    pairs = {')': '(', ']': '[', '}': '{'}

    # Йдемо по рядку символ за символом
    for char in expression:
        if char in '([{':
            # Символ - відкриваюча дужка -> кладемо її в стек
            push(stack, char)

        elif char in ')]}':
            # Символ - закриваюча дужка
            if is_empty(stack):
                # Закривати нічого - відкриваючої дужки не було зовсім
                return False

            # Дістаємо останню (найближчу) відкриваючу дужку зі стека
            top = pop(stack)

            if top != pairs[char]:
                # Дістана дужка не відповідає поточній закриваючій -> дужки переплутані
                return False

    # Якщо після проходу всього рядка стек порожній - усі дужки знайшли свою пару
    return is_empty(stack)

print(is_balanced("(a+b)*[c-d]"))     # True
print(is_balanced("([a+b)]"))          # False
print(is_balanced("{[()]}"))           # True
print(is_balanced("(("))               # False


