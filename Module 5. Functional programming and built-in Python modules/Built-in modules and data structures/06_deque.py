#
# deque([5, 6, 7, 8, 9], maxlen=5)

'''
Як видно з прикладу, нові елементи витісняють старіші, але розмір залишається незмінним.
В усьому іншому deque веде себе точно як список Python.

Двосторонні черги поєднують в собі можливості стеків та черг, дозволяючи додавати та видаляти
елементи з обох кінців. Це робить їх винятково гнучкими для різних сценаріїв. Deques часто
використовуються там, де потрібен швидкий доступ до елементів з обох кінців структури,
наприклад, в алгоритмах, що вимагають обробки буферів або паліндромів, а також у задачах
з різними пріоритетами.

Уявімо, що у нас є список завдань на день, де кожне завдання описано як словник із двома
атрибутами: тип завдання (швидке або повільне) та його назва. Наша задача — розподілити ці
завдання таким чином, щоб швидкі завдання виконувалися першими. Для цього ми використаємо
двосторонню чергу, яка дозволяє нам додавати елементи як на початок, так і в кінець черги.

Завдання, визначені як "fast", повинні виконуватися в першу чергу, тому вони мають більший
пріоритет. Натомість "slow" завдання можуть зачекати і ми додаємо їх в кінець черги, виконуючи
після всіх швидких завдань.

Мета цієї задачі — продемонструвати, як можна використовувати двосторонню чергу для контролю
пріоритету завдань.
'''

# ✂️ Цей код можна запустити!

from collections import deque

# Список завдань, де кожне завдання - це словник
tasks = [
    {"type": "fast", "name": "Помити посуд"},
    {"type": "slow", "name": "Подивитись серіал"},
    {"type": "fast", "name": "Вигуляти собаку"},
    {"type": "slow", "name": "Почитати книгу"}
]

# Ініціалізація черги завдань
task_queue = deque()

# Розподіл завдань у чергу відповідно до їх пріоритету
for task in tasks:
    if task["type"] == "fast":
        task_queue.appendleft(task)  # Додавання на високий пріоритет
        print(f"Додано швидке завдання: {task['name']}")
    else:
        task_queue.append(task)  # Додавання на низький пріоритет
        print(f"Додано повільне завдання: {task['name']}")

# Виконання завдань
while task_queue:
    task = task_queue.popleft()
    print(f"Виконується завдання: {task['name']}")

