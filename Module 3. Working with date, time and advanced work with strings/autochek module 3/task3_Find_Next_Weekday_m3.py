'''
Крок третій. В основному завданні є умова. "Оскільки дні народження колег можуть припадати на вихідні, ваша функція також повинна враховувати це та переносити дату привітання на наступний робочий день, якщо це необхідно".

Отже, щоб виконати таку дію нам потрібен пошук дати наступного конкретного дня тижня від конкретної дати.

На цьому кроці вам потрібно створити функцію find_next_weekday, яка дозволяє знайти дату наступного конкретного дня тижня після заданої дати. Це особливо корисно для перенесення дати вітання колег, якщо їхні дні народження припадають на вихідні.

Параметри:

start_date - дата, від якої починається пошук (у форматі об'єкта дати).
weekday - день тижня, який потрібно знайти. Приймає значення від 0 (понеділок) до 6 (неділя). За замовчуванням встановлено 0 (понеділок), оскільки це найчастіше потрібно для перенесення дат.
Функція має знайти та повернути наступну дату заданого дня тижня, починаючи від start_date. Наприклад, якщо start_date — це вівторок, і вам потрібен наступний понеділок, функція повинна повернути дату наступного понеділка.

Наприклад, ви хочете знайти наступний понеділок і наступну п'ятницю після 26 березня 2024 року. Використання вашої функції має виглядати так:

start_date = string_to_date("2024.03.26")  # Перетворення рядка на дату
next_monday = find_next_weekday(start_date, 0)  # Знайти наступний понеділок
print(next_monday)
next_friday = find_next_weekday(start_date, 4)  # Знайти наступну п'ятницю
print(next_friday)
Повинно призводити до виведення:

2024 - 04 - 01
2024 - 03 - 29
Бо для вівторка 26 березня 2024 року наступна п'ятниця буде 29 березня на тому ж тижні, а наступний понеділок вже 1 квітня наступного тижня. Приклад демонструє, що функція універсальна і може застосовуватися для будь-якого дня тижня.
'''
from datetime import datetime, timedelta

def string_to_date(date_string):
    """
    Ця функція приймає рядок (наприклад, "2024.03.26") 
    і перетворює його на об'єкт дати, з яким Python вміє рахувати.
    """
    return datetime.strptime(date_string, "%Y.%m.%d").date()


def find_next_weekday(start_date, weekday=0):
    """
    Головна функція: шукає дату наступного конкретного дня тижня.
    weekday=0 означає, що за замовчуванням ми шукаємо Понеділок.
    """
    # 1. Дізнаємося, який день тижня у нашої початкової дати.
    # Метод .weekday() повертає число від 0 (понеділок) до 6 (неділя).
    current_weekday = start_date.weekday()
    
    # 2. Рахуємо різницю в днях між цільовим днем (weekday) і поточним.
    # Магія % 7 (залишок від ділення) потрібна для того, щоб коло днів 
    # завжди крутилося вперед, навіть якщо цільовий день уже пройшов на цьому тижні.
    days_ahead = (weekday - current_weekday) % 7
    
    # 3. Перевірка на "сьогоднішній день":
    # Якщо days_ahead дорівнює 0, це означає, що сьогодні вже той самий день, який ми шукаємо.
    # Але оскільки нам потрібен саме НАСТУПНИЙ день (через тиждень), ми примусово зсуваємо його на 7 днів.
    if days_ahead == 0:
        days_ahead = 7
    
    # 4. Робимо "стрибок у часі" за допомогою timedelta. #timedelta - це інструмент для додавання або віднімання часу від дати.
    # Додаємо вирахувану кількість днів (days_ahead) до нашої початкової дати.
    next_date = start_date + timedelta(days=days_ahead)
    
    # 5. Повертаємо готову нову дату назад у програму.
    # Важливо: цей return стоїть строго на рівні 4-х пробілів (не всередині if),
    # тому функція завжди поверне результат, а не None.
    return next_date


# --- ТЕСТОВИЙ БЛОК ДЛЯ ПЕРЕВІРКИ ---
# (Цей блок можна запускати, щоб подивитися, як працює програма)

# Створюємо дату: 26 березня 2024 року (це Вівторок, тобто день №1)
#start_date = string_to_date("2024.03.26")  
start_date = string_to_date(input("Введіть дату у форматі YYYY.MM.DD: "))  # Дозволяє користувачу ввести дату

# Шукаємо наступний понеділок (день №0)
# Вівторок (1) -> Понеділок (0). Математика: (0 - 1) % 7 = 6 днів вперед.
# 26 березня + 6 днів = 1 квітня.
next_monday = find_next_weekday(start_date, 0)  
print(f"Наступний понеділок: {next_monday}")    # Виведе: 2024-04-01

# Шукаємо наступну п'ятницю (день №4)
# Вівторок (1) -> П'ятниця (4). Математика: (4 - 1) % 7 = 3 дні вперед.
# 26 березня + 3 дні = 29 березня.
next_friday = find_next_weekday(start_date, 4)  
print(f"Наступна п'ятниця: {next_friday}")     # Виведе: 2024-03-29
        
        
    
