'''
На п'ятому кроці ми виконаємо обробку вихідних днів.

Вам потрібно написати функцію adjust_for_weekend, яка приймає як аргумент дату народження birthday і перевіряє, чи припадає ця дата на вихідний (суботу або неділю). Якщо дата народження припадає на вихідний, функція знаходить наступний понеділок і повертає його як нову дату святкування. Інакше, якщо дата народження випадає на будній день, функція повертає оригінальну дату народження.
'''

from datetime import datetime, timedelta


# ФУНКЦІЯ 1: перетворює рядок "2024.03.30" → об'єкт datetime.date(2024, 3, 30)
# strptime читає рядок за шаблоном, .date() прибирає час
def string_to_date(date_string):
    return datetime.strptime(date_string, "%Y.%m.%d").date()


# ФУНКЦІЯ 2: знаходить дату наступного конкретного дня тижня після start_date
# weekday: 0=пн, 1=вт, 2=ср, 3=чт, 4=пт, 5=сб, 6=нд
# Приклад: якщо start_date — субота, find_next_weekday(date, 0) поверне наступний понеділок
def find_next_weekday(start_date, weekday):
    # рахуємо скільки днів до потрібного дня тижня
    days_ahead = weekday - start_date.weekday()
    # якщо результат 0 або від'ємний — цей день вже минув на цьому тижні,
    # тому додаємо 7 щоб перейти на наступний тиждень
    if days_ahead <= 0:
        days_ahead += 7
    return start_date + timedelta(days=days_ahead)


# ФУНКЦІЯ 3: головна функція цього завдання
# Перевіряє чи день народження припадає на вихідний
# Якщо так — переносить на наступний понеділок
# Якщо ні — повертає оригінальну дату
def adjust_for_weekend(birthday):
    # .weekday() повертає число: 0=пн ... 4=пт, 5=сб, 6=нд
    # >= 5 означає субота або неділя
    if birthday.weekday() >= 5:
        # переносимо на наступний понеділок (0 = понеділок)
        birthday = find_next_weekday(birthday, 0)
    return birthday