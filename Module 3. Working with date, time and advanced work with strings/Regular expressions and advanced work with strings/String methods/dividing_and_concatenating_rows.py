'''
Останній метод який ми розглянемо це isdigit(). 
Він використовується для перевірки, чи складається рядок повністю з цифр.
Цей метод повертає True, якщо всі символи в рядку є цифрами та рядок складається принаймні з одного символу, 
інакше повертає False.
'''

number = "12345"
print(number.isdigit())  # Виведе: True

text = "Number123"
print(text.isdigit())  # Виведе: False

'''
У цьому прикладі, isdigit() повертає True для рядка "12345", оскільки він складається виключно з цифр. 
Для рядка "Number123", метод повертає False, оскільки він містить інші символи, крім цифр.
'''

#Можна застосовувати для перевірки, чи ввів користувач число.
