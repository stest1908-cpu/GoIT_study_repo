#Різниця між двома множинами включає елементи, які містяться в першій множині, але не містяться в другій. 
# Можна також використовувати оператор - або метод difference:


a = {1, 2, 3}
b = {3, 4, 5}
print(a.difference(b))  # {1, 2}
print(a - b)  # {1, 2}
print(b - a)  # {4, 5} - різниця між двома множинами, які містяться в другій множині, але не містяться в першій

d = {1, 2, 3, 6, 5}
e = {2, 3, 4, 5}
print(d - e)  # {1, 6}
print(d.difference(e))  # {1, 6}