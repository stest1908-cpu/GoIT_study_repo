#Метод sort() у списках Python використовується для сортування елементів списку в порядку зростання або спадання. 
# Цей метод модифікує вихідний список, тобто сортування відбувається "на місці", і він не створює новий відсортований список.

#За замовчуванням sort() впорядковує елементи списку за зростанням, від меншого до більшого.

nums = [3, 1, 4, 1, 5, 9, 2]
nums.sort()
print(nums)  # Виведе [1, 1, 2, 3, 4, 5, 9]

#Якщо потрібно відсортувати елементи в порядку спадання, використовуй аргумент reverse=True.

nums.sort(reverse=True)
print(nums)  # Виведе [9, 5, 4, 3, 2, 1, 1]

#Метод sort() також дозволяє сортувати за ключем, який визначає, як порівнювати елементи.
#Наприклад, у наступному прикладі ми відсортуємо список за довжиною слова у списку.

words = ["banana", "apple", "cherry", "kiwi"]
words.sort(key=len)
print(words)  # Виведе ['kiwi', 'apple', 'banana', 'cherry']
words.sort(key=len, reverse=True)
print(words)  # Виведе ['banana', 'cherry', 'apple', 'kiwi']

#Вбудований метод sorted() у Python використовується для сортування колекцій. 
# Він відрізняється від методу sort(), який застосовується безпосередньо до списку, 
# та змінює його: sorted() повертає новий відсортований об'єкт, залишаючи вихідний об'єкт без змін.
#  Метод також використовує аргумент reverse=True, щоб відсортувати об'єкти у зворотному порядку, 
# та за допомогою аргументу key можна вказати функцію, яка буде застосовуватися для визначення порядку сортування.

#Сортування списку:
nums = [3, 1, 4, 1, 5, 9, 2]
sorted_nums = sorted(nums)
print(sorted_nums)  # Виведе [1, 1, 2, 3, 4, 5, 9]

#Сортування у зворотному порядку:
sorted_nums_desc = sorted(nums, reverse=True)
print(sorted_nums_desc)  # Виведе [9, 5, 4, 3, 2, 1, 1] 

#Сортування за довжиною:
words = ["banana", "apple", "cherry", "kiwi"]
sorted_words = sorted(words, key=len)
print(sorted_words)  # Виведе ['kiwi', 'apple', 'banana', 'cherry']

#Сортування за довжиною у зворотному порядку:
sorted_words_desc = sorted(words, key=len, reverse=True)
print(sorted_words_desc)  # Виведе ['banana', 'cherry', 'apple', 'kiwi']

