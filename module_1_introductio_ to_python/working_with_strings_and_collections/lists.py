#Щоб повернути елемент за індексом i та видалити його зі списку,
#  ми використовуємо метод pop(i). За замовчуванням i = -1, і метод повертає останній елемент списку.

#Нехай у нас є наступний список із букв:

chars = ['a', 'b', 'c']
print(chars)  # Виведе: ['a', 'b', 'c']
last = chars.pop(1)  # Видаляє 'b' і повертає його
print(last)  # Виведе: 'b'
print(chars)  # Виведе: ['a', 'c']

#Якщо виникає потреба розширити один список іншим,
#  то використовують метод extend. Наприклад, ми маємо два списки chars та numbers і хочемо,
#  щоб у список chars додалися всі елементи списку numbers.


chars = ['a', 'b', 'c']
numbers = [1, 2]
chars.extend(numbers)
print(chars)  # Виведе: ['a', 'b', 'c', 1, 2]

numbers.extend(chars)
print(numbers)  # Виведе: [1, 2, 'a', 'b', 'c']

#Для вставки елемента x на позицію з індексом i у список ми використовуємо метод insert(i, x). 
