#Список — це впорядкований змінюваний контейнер даних. 
# Списки не диктують розробнику тип даних, який можна помістити в цей контейнер,
#  і можуть містити будь-які типи даних у будь-якому зручному порядку.
#  Це одна з найбільш універсальних і важливих структур даних.

#Існують два способи створити порожній список:

