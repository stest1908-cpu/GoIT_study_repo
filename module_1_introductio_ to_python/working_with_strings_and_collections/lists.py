#Списки можуть містити будь-які типи даних, включаючи інші списки:
my_list = [1, 2, 3, 'four', 'five', [6, 7, 8]]
#Списки підтримують індексацію, що дозволяє отримувати доступ до окремих елементів за їх позицією:
print(my_list[0])  # Виведе: 1
print(my_list[3])  # Виведе: 'four'
#Списки також підтримують негативну індексацію, яка дозволяє отримувати доступ до елементів з кінця списку:
print(my_list[-1])  # Виведе: [6, 7, 8]
print(my_list[-2])  # Виведе: 'five'

#список із п'ятьох чисел.
my_list2 = [1, 2, 3, 4, 5]
print(my_list2)  # Виведе: [1, 2, 3, 4, 5]
print(my_list2[0])  # Виведе: 1
print(my_list2[2:5])  # Виведе: [3, 4, 5]
print(type(my_list2))  # Виведе: <class 'list'>
print(len(my_list2))  # Виведе: 5

#Списки можуть містити різні типи даних:
my_list3 = [1, "Hello", 3.14]
print(my_list3)  # Виведе: [1, 'Hello', 3.14]
print(type(my_list3))  # Виведе: <class 'list'>

#Якщо ви хочете додати щось до свого списку, використовуйте метод append()
