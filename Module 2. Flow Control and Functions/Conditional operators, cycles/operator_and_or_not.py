#Оператор and

#Оператор and використовується для перевірки, чи обидві умови є істинними. Вираз з and вважається True тільки тоді, коли обидва операнди істинні.
a = True and False  # False
print(a)

'''
Таблиця істинності для and:
A | B | A and B
True | True | True
True | False | False
False | True | False
False | False | False

Ця таблиця показує, що вираз A and B буде істинним тільки тоді,
 коли обидва операнди A і B істинні.
'''

#Оператор or 

'''Оператор or перевіряє, чи хоча б одна з умов є істинною. Вираз із or вважається True, "
"якщо принаймні один із операндів є істинним:'''

a = True or False  # True
print(a)

'''
Таблиця істинності для or:
A | B | A or B
True | True | True
True | False | True
False | True | True
False | False | False

З таблиці видно, що вираз A or B є істинним у всіх випадках, 
крім випадку, коли обидва операнди є неправдивими.
''' 

#Оператор not

'''
Оператор not використовується для інвертування істинності операнду.
 Якщо операнд істинний, not перетворює його на неправдивий, і навпаки:'''

a = not 2 < 0  # True
print(a)

#Example
a = int(input("Enter a number: "))

if not a < 2:
    print(f"The number {a} is not less than 2/True")
else:
    print(f"The number {a} is less than 2/False")

#У цьому прикладі, оскільки 2 < 0 є неправдивим (False), оператор not перетворює його на True.

'''
Таблиця істинності для not:
A | not A
True | False
False | True
'''
