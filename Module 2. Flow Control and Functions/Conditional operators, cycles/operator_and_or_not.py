'''
написати програми, яка для заданого числа:

Виводить "Fizz", якщо число кратне якомусь певному числу (наприклад, 3);
Виводить "Buzz", якщо число кратне іншому певному числу (наприклад, 5);
Виводить "FizzBuzz", якщо число кратне обом цим числам;
В іншому випадку виводить саме число.
'''
# Задаємо конкретне число
num = int(input())
# Перевіряємо кратність
if num % 3 == 0 and num % 5 == 0:
    print("FizzBuzz")
elif num % 3 == 0:
    print("Fizz")
elif num % 5 == 0:
    print("Buzz")
else:
    print(num)
'''
Умова if num % 3 == 0 and num % 5 == 0 перевіряє, чи введене число кратне і 3, і 5 одночасно.
 Ця перевірка стоїть першою, оскільки вона є найспецифічнішою.

Якщо ця умова виконується, виводиться "FizzBuzz".
Якби ця перевірка була після інших, вона б ніколи не виконувалася,
тому що більш загальні умови (кратність 3 або 5) вже б були виконані.
Далі elif num % 3 == 0 перевіряє, чи число кратне тільки 3.
Ця умова виконується тільки якщо попередня умова (кратність і 3, і 5) не виконалася.
Якщо це правда, виводиться "Fizz". Умова elif num % 5 == 0 перевіряє, чи число кратне тільки 5. 
Як і попередня, ця умова виконується лише тоді, коли попередні перевірки не виявилися істинними. 
У випадку виконання цієї умови виводиться "Buzz". Якщо жодна з вищезазначених умов не виконалася, то else гарантує, що буде виведене саме число.

Порядок цих умов є ключовим, бо він забезпечує, що найспецифічніша перевірка - кратність і 3, і 5 має пріоритет, 
а потім перевіряються менш специфічні випадки - кратність окремо 3 або 5. Це запобігає випадкам, коли числа, які кратні і 3, і 5, 
були б неправильно оброблені через виконання менш специфічних умов.

 '''