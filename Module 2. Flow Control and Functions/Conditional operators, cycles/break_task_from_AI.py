'''
Твоє завдання: "Оболонський Склад: Secure Login"
Напиши програму, яка імітує вхід у складську систему.

Логіка роботи:

1. Налаштування:

- Створи змінну correct_password (наприклад, "Admin123").

- Створи лічильник attempts = 0.

2. Цикл: Запусти нескінченний цикл while True.

3. Ввід: Кожного разу всередині циклу запитуй пароль у користувача.

4. Перевірка успіху: Якщо пароль вірний:

- Виведи: "Доступ дозволено! Склад відчинено."

- Використай break, щоб вийти з програми.

5. Перевірка помилки: Якщо пароль невірний:

- Збільшуй attempts на 1.

- Виведи: "Невірний пароль! Залишилося спроб: {3 - attempts}".

6.Блокування: Якщо attempts стає рівним 3:

- Виведи: "Система заблокована! Викличте охорону Оболоні."

- Використай break, щоб завершити програму.
'''
correct_password = "Admin123"
attempts = 0

while True:
    user_input = input("Введіть пароль: ")
    if user_input == correct_password:
        print("Доступ дозволено! Склад відчинено.")
        break
    else:
        attempts += 1
        print(f"Невірний пароль! Залишилося спроб: {3 - attempts}")
        if attempts == 3:
            print("Система заблокована! Викличте охорону Оболоні.")
            break