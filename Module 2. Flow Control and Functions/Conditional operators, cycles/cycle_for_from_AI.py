'''
Завдання: "Аналізатор пароля/артикула"
Уяви, що тобі як QA-тестувальнику потрібно перевірити, чи містить введений серійний номер товару або пароль цифри. Це класична задача для циклу for.

Умова:

Користувач вводить рядок (наприклад, пароль або артикул товару).

Створи змінну-лічильник digit_count = 0.

Використай цикл for, щоб пройтися по кожному символу рядка.

Всередині циклу за допомогою if перевір, чи є символ цифрою.

Підказка: У Python є зручний метод .isdigit(). Використовуй його так: if char.isdigit():

Якщо це цифра, збільшуй digit_count на 1.

Після циклу виведи повідомлення: "У вашому рядку знайдено [кількість] цифр".
'''

password = input("Введіть пароль: ")

digit_count = 0

for char in password: 
    if char.isdigit():
        digit_count += 1

# Виводимо результат ПІСЛЯ циклу
if digit_count > 0:
    print(f"У вашому рядку знайдено {digit_count} цифр")
else:
    # Ось твоя перевірка "на вошивість" (QA стиль)
    print("Помилка: артикул повинен містити хоча б одну цифру!")