# Оголошуємо функцію з двома параметрами
def format_string(string, length):
    
    # Якщо рядок більший або рівний length — повертаємо без змін
    if len(string) >= length:
        return string
    else:
        # Розраховуємо кількість пробілів за формулою
        spaces = (length - len(string)) // 2
        
        # Створюємо рядок з пробілів і додаємо наш рядок
        result = " " * spaces + string
        
        # Повертаємо відцентрований рядок
        return result

# Отримуємо дані від користувача
