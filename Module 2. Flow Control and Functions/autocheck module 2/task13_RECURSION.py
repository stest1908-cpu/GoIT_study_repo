'''
Ми проводимо розіграш призів серед перших 50 підписників ютуб-каналу.
Ми маємо 7 призів для розіграшу. Може виникнути питання, скільки різних списків переможців ми можемо отримати під час розіграшу?
Для цього ми будемо використовувати формулу сполучень без повторень

Cnk = n! / ((n - k)! · k!)

де n — це загальна кількість людей (випадків), а k — кількість людей, які отримали призи.

Напишіть функцію number_of_groups, яка приймає параметри n та k, і за допомогою функції factorial повертає нам скільки різних списків переможців ми можемо отримати при розіграші

Задачі:

1.Створіть функцію number_of_groups, яка приймає два аргументи: n - загальна кількість людей та k - кількість переможців.
2.У функції number_of_groups, використовуйте функцію factorial для обчислення факторіалів відповідно до формули сполучень: Cnk = n! / ((n - k)! · k!).
3.Обчислення здійснюється шляхом виклику функції factorial для отримання факторіалів n, n - k та k.
4.Поверніть результат цього обчислення.
Очікуваний результат:

Функція number_of_groups повертає кількість можливих різних списків переможців.

Зверніть увагу на те, які великі значення ми отримуємо для факторіала. Рекурсивні висловлювання треба завжди застосовувати з обережністю при обчисленнях, щоб не отримати переповнення пам'яті.
'''

# Рекурсивна функція для обчислення факторіалу
def factorial(n):
    if n < 2:           # базовий випадок: 0! = 1, 1! = 1
        return 1
    else:
        return n * factorial(n - 1)  # рекурсія: 5! = 5 * 4 * 3 * 2 * 1
# Наприклад: factorial(3) → 3 * factorial(2) → 3 * 2 * factorial(1) → 3 * 2 * 1 = 6

# Функція обчислює кількість можливих груп переможців
# Формула сполучень: n! / (k! * (n-k)!)
def number_of_groups(n, k):
    # factorial(n)     — факторіал загальної кількості людей
    # factorial(k)     — факторіал кількості переможців
    # factorial(n-k)   — факторіал різниці
    result = factorial(n) // (factorial(k) * factorial(n - k))
    return result

# 50 підписників, 7 призів → скільки варіантів списків переможців?
print(number_of_groups(50, 7))  # 99884400

# Юніт тести — перевіряємо правильність функцій
assert factorial(0) == 1        # 0! = 1
assert factorial(1) == 1        # 1! = 1
assert factorial(5) == 120      # 5! = 120
assert number_of_groups(50, 7) == 99884400
assert number_of_groups(10, 2) == 45
